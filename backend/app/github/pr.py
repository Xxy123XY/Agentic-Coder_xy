import asyncio
from datetime import datetime
from app.github.client import get_repo
from app.observability.logger import get_logger

logger = get_logger(__name__)


async def create_pull_request(
    repo_full_name: str,
    issue_number: int,
    issue_title: str,
    diff: str,
    test_code: str,
    analysis: dict,
) -> str:
    return await asyncio.to_thread(
        _create_pr_sync,
        repo_full_name, issue_number, issue_title, diff, test_code, analysis,
    )


def _create_pr_sync(
    repo_full_name: str,
    issue_number: int,
    issue_title: str,
    diff: str,
    test_code: str,
    analysis: dict,
) -> str:
    repo = get_repo(repo_full_name)
    timestamp = datetime.now().strftime('%m%d%H%M%S')
    branch_name = f"fix/issue-{issue_number}-{timestamp}"
    base_branch = repo.default_branch

    base_sha = repo.get_branch(base_branch).commit.sha
    repo.create_git_ref(ref=f"refs/heads/{branch_name}", sha=base_sha)
    logger.info("branch_created", branch=branch_name)

    # Commit test file — with full error handling
    test_content = test_code.strip() if test_code else f"# Automated test for issue #{issue_number}\n"
    test_file_path = f"tests/test_issue_{issue_number}_{timestamp}.py"

    try:
        repo.create_file(
            path=test_file_path,
            message=f"test: add automated test for issue #{issue_number}",
            content=test_content,
            branch=branch_name,
        )
        logger.info("test_file_created", path=test_file_path)
    except Exception as e:
        logger.warning("test_file_creation_failed", error=str(e))
        # Fallback: create a simple placeholder so branch has at least one commit
        try:
            repo.create_file(
                path=f"fixes/issue_{issue_number}_{timestamp}.md",
                message=f"fix: automated fix for issue #{issue_number}",
                content=f"# Fix for issue #{issue_number}\n\nSee diff in PR description.",
                branch=branch_name,
            )
        except Exception as e2:
            logger.error("fallback_file_creation_failed", error=str(e2))

    body = f"""## Automated fix for #{issue_number}

**Module:** {analysis.get('module', 'unknown')}
**Severity:** {analysis.get('severity', 'unknown')}

### Expected behavior
{analysis.get('expected_behavior', 'N/A')}

### Actual behavior
{analysis.get('actual_behavior', 'N/A')}

### Proposed diff
```diff
{diff}
```

---
Generated by multi-agent-orchestrator
Closes #{issue_number}
"""

    pr = repo.create_pull(
        title=f"Fix: {issue_title}",
        body=body,
        head=branch_name,
        base=base_branch,
    )

    logger.info("pr_created", url=pr.html_url, issue=issue_number)
    return pr.html_url